import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { doc, setDoc, getDoc, getDocs, deleteDoc, addDoc, collection, serverTimestamp } from "firebase/firestore";
import fs from "fs";
const env = await initializeTestEnvironment({ projectId: "thai-news-kr", firestore: { rules: fs.readFileSync("firestore.rules", "utf8"), host: "127.0.0.1", port: 8096 } });
await env.withSecurityRulesDisabled(async c => { await setDoc(doc(c.firestore(), "config/admins"), { uids: ["adm"] }); });
const anon = env.unauthenticatedContext().firestore(), adm = env.authenticatedContext("adm").firestore(), usr = env.authenticatedContext("u1").firestore();
const R = []; const t = async (name, ok, p) => { try { await (ok ? assertSucceeds(p) : assertFails(p)); R.push(["OK ", name]); } catch (e) { R.push(["BAD", name, String(e.message).slice(0, 120)]); } };
const id = "osm-node-421263061", ts = serverTimestamp();
await t("운영자 쓰기 n=2 허용", true, setDoc(doc(adm, "placeflags", id), { id, n: 2, st: "", at: ts }));
await t("운영자 폐업 확인 st=closed 허용", true, setDoc(doc(adm, "placeflags", id), { id, n: 2, st: "closed", at: ts }));
await t("운영자 되돌리기 st='' 허용", true, setDoc(doc(adm, "placeflags", id), { id, n: 2, st: "", at: ts }));
await t("구글 가게 id 허용", true, setDoc(doc(adm, "placeflags", "gmap-255598704886170663"), { id: "gmap-255598704886170663", n: 1, st: "", at: ts }));
await t("익명 쓰기 거부", false, setDoc(doc(anon, "placeflags", id), { id, n: 9, st: "", at: ts }));
await t("일반 로그인 쓰기 거부", false, setDoc(doc(usr, "placeflags", id), { id, n: 9, st: "", at: ts }));
await t("다른 키(memo) 거부", false, setDoc(doc(adm, "placeflags", id), { id, n: 2, st: "", at: ts, memo: "x" }));
await t("id ≠ 문서 id 거부", false, setDoc(doc(adm, "placeflags", id), { id: "osm-node-1", n: 2, st: "", at: ts }));
await t("모르는 모양 문서 id 거부", false, setDoc(doc(adm, "placeflags", "evil"), { id: "evil", n: 2, st: "", at: ts }));
await t("st 다른 값 거부", false, setDoc(doc(adm, "placeflags", id), { id, n: 2, st: "gone", at: ts }));
await t("n 음수 거부", false, setDoc(doc(adm, "placeflags", id), { id, n: -1, st: "", at: ts }));
await t("at 클라이언트 시각 거부", false, setDoc(doc(adm, "placeflags", id), { id, n: 2, st: "", at: new Date() }));
await t("익명 읽기 허용(공개 숫자)", true, getDoc(doc(anon, "placeflags", id)));
await t("익명 목록 허용", true, getDocs(collection(anon, "placeflags")));
await t("지우기 거부(운영자도)", false, deleteDoc(doc(adm, "placeflags", id)));
const rep = (type, memo) => ({ id: "place:" + id, kind: "place", type, memo, url: "https://p-max168.github.io/thai-news-kr/#places", ed: "", at: serverTimestamp() });
await t("신고 type closed 허용(새 규칙)", true, addDoc(collection(anon, "reports"), rep("closed", "")));
await t("신고 etc + [폐업·없어짐] 메모 허용(지금 모양)", true, addDoc(collection(anon, "reports"), rep("etc", "[폐업·없어짐] 문 닫힘")));
await t("신고 모르는 type 거부", false, addDoc(collection(anon, "reports"), rep("gone", "")));
await t("신고 익명 읽기 여전히 거부", false, getDocs(collection(anon, "reports")));
await t("그 밖 경로 거부", false, setDoc(doc(anon, "other", "x"), { a: 1 }));
R.forEach(r => console.log(r.join(" | ")));
console.log("요약:", R.filter(r => r[0] === "OK ").length, "OK /", R.filter(r => r[0] === "BAD").length, "BAD");
await env.cleanup(); process.exit(0);
